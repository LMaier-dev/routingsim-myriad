#!/usr/bin/env python3
"""Emit any candidate topology as a routingsim .txt PLUS its .ring.ini, so
it can be run under MyriadGP exactly like the existing topologies.

The topo_lib families here have no native ring plan, so rings are mined with
the stock cover_rings (cycle_basis), isolating the topology rather than the
cover. (Topologies that SHIP a ring plan are built by ringpipe.py instead.)

    python3 export.py --families gabriel rgg --sizes 250 1000
    python3 export.py --all --sizes 500          # every topo_lib family, one size

Writes topologies to csv/ and ring labels to ringlabels/, using the same
naming the existing tooling expects.
"""
import argparse
import datetime
import os
import sys

import networkx as nx

HERE = os.path.dirname(os.path.abspath(__file__))
MYRIAD = os.path.dirname(HERE)
TOPO_DIR = os.path.join(HERE, "csv")             # topology .txt files
RINGLABELS_DIR = os.path.join(HERE, "ringlabels")   # ring-label .ini files
sys.path.insert(0, HERE)
sys.path.insert(0, MYRIAD)

from metrics import score, cover_rings, rings_to_membership
from topo_lib import FAMILIES

RING_ID_BASE = 1_000_000          # ring ids count DOWN from here, as topo2rings does


def write_topology(g, path, provenance):
    n, m = g.number_of_nodes(), g.number_of_edges()
    sp = nx.average_shortest_path_length(g) if n <= 1200 else None
    with open(path, "w") as f:
        f.write(f"# : {provenance}\n")
        f.write(f"# time: {datetime.datetime.now()}\n")
        f.write(f"# size: {n}\n# edges: {m}\n# connected: {nx.is_connected(g)}\n")
        f.write(f"# average degree: {2 * m / n}\n")
        f.write(f"# density: {nx.density(g)}\n")
        f.write(f"# diameter: {nx.diameter(g) if n <= 3000 else 'n/a'}\n")
        f.write(f"# average clustering: {nx.average_clustering(g)}\n")
        f.write(f"# average shortest path length: {sp if sp else 'n/a'}\n")
        f.write(f"{n}\t{m}\n")
        for u, v in g.edges():      # both directions, as every other topology does
            f.write(f"{u}\t{v}\n{v}\t{u}\n")


def write_ringlabels(g, rings, path, header):
    member, _ = rings_to_membership(g, rings)
    with open(path, "w") as f:
        for line in header:
            f.write(f"# {line}\n")
        for v in sorted(g.nodes()):
            labels = ",".join(str(RING_ID_BASE - i) for i in sorted(member[v]))
            f.write(f'**.Node{v}.*.ringLabel = "{labels}"\n')


def export(fam, n, seed=0, cap=10, topo_dir=TOPO_DIR, ini_dir=RINGLABELS_DIR, quiet=False):
    g, rings = FAMILIES[fam](n, seed=seed)
    native = rings is not None
    if not native:
        rings = cover_rings(g, cap)
    s = score(g, rings)          # raises on an unwalkable ring set

    # Real node count drifts from the target (giant component, ring gluing), so
    # name by what was actually built -- the ini must match the .txt exactly.
    # txt and ini share a stem so --basis native resolves the ini as stem+".ini".
    stem = f"{fam}_n{s['n']}_seed{seed}"
    kind = "native.ring" if native else f"tree.m{cap}.ring"
    os.makedirs(topo_dir, exist_ok=True)
    os.makedirs(ini_dir, exist_ok=True)
    topo = os.path.join(topo_dir, f"{stem}.{kind}.txt")
    ini = os.path.join(ini_dir, f"{stem}.{kind}.ini")

    write_topology(g, topo, f"generated with myriad_topologies/topo_lib.py family={fam} seed={seed}")
    hdr = [f"ringLabel lines generated by myriad_topologies/export.py from {stem}.{kind}.txt",
           f"family={fam} rings={'native plan' if native else f'cycle_basis (tree) cap={cap}'}",
           f"nodes={s['n']} edges={s['m']} avgdeg={s['avgdeg']:.2f} rings={s['rings']} echo={s['echo']}",
           f"fan-out(sum k*(k-1))={s['fan']} fan/n={s['fan_n']:.2f} max rings/node={s['maxk']}",
           f"transitions: {s['pairs']} ring pairs, {s['spof']} spof ({s['spofpct']:.1f}%)",
           f"ring-graph components={s['comp']} biconnected={s['biconn']} "
           f"diameter={s['diam']} mean ring size={s['meanring']:.1f}"]
    if s["comp"] > 1:
        hdr.append("WARNING: ring graph partitioned — routing cannot cross components")
    if s["ringless"]:
        hdr.append(f"WARNING: {s['ringless']} node(s) in no ring (unroutable)")
    write_ringlabels(g, rings, ini, hdr)

    if not quiet:
        print(f"{fam:13} n={s['n']:5} fan/n={s['fan_n']:6.2f} spof={s['spofpct']:5.1f}% "
              f"diam={s['diam']:4} 2con={'Y' if s['biconn'] else 'n'}")
        print(f"              {topo}")
        print(f"              {ini}")
    return s, topo, ini


def _selfcheck():
    """An exported pair must round-trip: the .txt reparses to the same graph and
    every ringLabel node exists. A mismatch here silently mis-simulates."""
    import tempfile
    sys.path.insert(0, HERE)
    from topo2rings import read_topology
    with tempfile.TemporaryDirectory() as d:
        s, topo, ini = export("delaunay", 120, topo_dir=d, ini_dir=d, quiet=True)
        g2 = read_topology(topo)
        assert g2.number_of_nodes() == s["n"], (g2.number_of_nodes(), s["n"])
        assert g2.number_of_edges() == s["m"], (g2.number_of_edges(), s["m"])
        assert nx.is_connected(g2)
        labelled = [l for l in open(ini) if l.startswith("**.Node")]
        assert len(labelled) == s["n"], (len(labelled), s["n"])
        assert all('ringLabel = ""' not in l for l in labelled), "node with no ring"
    print("export selfcheck ok")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--families", nargs="+", default=["delaunay"])
    ap.add_argument("--all", action="store_true", help="every family in topo_lib")
    ap.add_argument("--sizes", type=int, nargs="+", default=[250])
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--cap", type=int, default=10, help="mined-ring size cap")
    ap.add_argument("--selfcheck", action="store_true")
    a = ap.parse_args()
    if a.selfcheck:
        return _selfcheck()
    fams = list(FAMILIES) if a.all else a.families
    for n in a.sizes:
        for fam in fams:
            try:
                export(fam, n, seed=a.seed, cap=a.cap)
            except Exception as e:
                print(f"{fam:13} n={n:5} FAILED: {type(e).__name__}: {e}")


if __name__ == "__main__":
    main()
